"""Opt-in PostgreSQL storage for A; the existing HTTP contract stays unchanged.

Schema creation is an explicit migration step. Runtime credentials need no CREATE
SCHEMA privilege. During the first migration we preserve BEGIN IMMEDIATE's
serialized write semantics with a transaction advisory lock, rather than silently
introducing lost updates in JSON read/modify/write operations.
"""
from contextlib import contextmanager
import os
import re
import sqlite3
import threading

_pools = {}
_pool_lock = threading.Lock()
IDENTIFIER = re.compile(r'^[a-z][a-z0-9_]{0,62}$')


def schema_name():
    name = os.environ.get('QAXC_DB_SCHEMA', 'a')
    if not IDENTIFIER.fullmatch(name) or name in {'public', 'b', 'pg_catalog', 'information_schema'}:
        raise ValueError('QAXC_DB_SCHEMA must be a dedicated A schema')
    return name


def enabled():
    return bool(os.environ.get('QAXC_DB_URL'))


def parameters(sql):
    """Translate qmark placeholders, preserving quoted SQL literals/identifiers."""
    result, quote, i = [], None, 0
    while i < len(sql):
        ch = sql[i]
        if ch == '%':
            result.append('%%'); i += 1; continue
        if quote:
            result.append(ch)
            if ch == quote:
                if i + 1 < len(sql) and sql[i + 1] == quote:
                    result.append(sql[i + 1]); i += 1
                else:
                    quote = None
        elif ch in {'\"', "'"}:
            quote = ch; result.append(ch)
        else:
            result.append('%s' if ch == '?' else ch)
        i += 1
    return ''.join(result)


class Row(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


def row_factory(cursor):
    names = [col.name for col in cursor.description] if cursor.description else []
    return lambda values: Row((name, value) for name, value in zip(names, values) if name != '_row_order')


class Connection:
    task_order_column = '_row_order'

    def __init__(self, raw):
        self.raw = raw

    def execute(self, statement, params=()):
        import psycopg
        sql = statement.strip()
        if sql.upper() == 'BEGIN IMMEDIATE':
            # Stable, per-database lock; released on commit/rollback, including errors.
            sql = "SELECT pg_advisory_xact_lock(hashtextextended(current_schema() || ':a-write',0))"
        if re.match(r'CREATE TABLE IF NOT EXISTS\s+', sql, re.I):
            sql = re.sub(r'\b(payload|result) TEXT\b', r'\1 JSONB', sql)
            if re.match(r'CREATE TABLE IF NOT EXISTS tasks\s*\(', sql, re.I):
                end = sql.rfind(')')
                sql = sql[:end] + ', _row_order BIGINT GENERATED BY DEFAULT AS IDENTITY' + sql[end:]
        try:
            return self.raw.execute(parameters(sql) if params else sql, params if params else None)
        except psycopg.IntegrityError as exc:
            # Existing callers already translate this family to an HTTP 409.
            raise sqlite3.IntegrityError('PostgreSQL constraint violation') from exc

    def executescript(self, script):
        # Only the application's static CREATE TABLE statements use this method.
        for statement in script.split(';'):
            if statement.strip():
                self.execute(statement)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()


def _pool():
    from psycopg_pool import ConnectionPool
    from psycopg.types.json import set_json_loads
    url, schema = os.environ['QAXC_DB_URL'], schema_name()
    if not url.startswith(('postgresql://', 'postgresql+psycopg://')):
        raise ValueError('QAXC_DB_URL must be PostgreSQL')
    key = (url, schema)
    with _pool_lock:
        if key not in _pools:
            def configure(conn):
                # A's existing domain code parses JSON strings; B uses its own engine.
                set_json_loads(lambda value: value.decode() if isinstance(value, bytes) else value, conn)
                with conn.cursor() as cur:
                    cur.execute('SELECT current_schema()')
                    if cur.fetchone()[0] != schema:
                        raise RuntimeError('A schema is missing; run the isolated migration first')
                conn.commit()
            _pools[key] = ConnectionPool(
                conninfo=url.replace('postgresql+psycopg://', 'postgresql://', 1),
                min_size=0, max_size=5, timeout=20,
                kwargs={'row_factory': row_factory,
                        'options': f'-csearch_path={schema},pg_catalog -clock_timeout=20000 -cstatement_timeout=30000',
                        'connect_timeout': 5}, configure=configure, open=True)
        return _pools[key]


@contextmanager
def connect():
    with _pool().connection() as raw:
        yield Connection(raw)


def close_pools():
    with _pool_lock:
        for pool in _pools.values():
            pool.close()
        _pools.clear()


def verify_shared_database(b_engine):
    """Compare actual server/database identities, never passwords or URL spellings."""
    query = 'SELECT current_database(),host(inet_server_addr()),inet_server_port(),current_schema()'
    with connect() as a_conn:
        a = tuple(a_conn.execute(query).fetchone().values())
    with b_engine.connect() as b_conn:
        b = tuple(b_conn.exec_driver_sql(query).fetchone())
    if a[:3] != b[:3] or a[3] == b[3]:
        raise RuntimeError('A/B must use the same PostgreSQL database with distinct schemas')
